export const dictionaries = { en, es, pt } as const;
export type Lang = keyof typeof dictionaries;
export const LANGS: Lang[] = ["en", "es", "pt"];

const ES = ["ES", "MX", "AR", "CO", "CL", "PE", "VE", "EC", "GT", "CU", "BO", "DO", "HN", "PY", "SV", "NI", "CR", "PA", "UY", "PR", "GQ"];
const PT = ["PT", "BR", "AO", "MZ", "CV", "GW", "ST", "TL"];

export const langFromCountry = (c: string): Lang => (ES.includes(c) ? "es" : PT.includes(c) ? "pt" : "en");

export function langFromBrowser(): Lang {
  const list = navigator.languages?.length ? navigator.languages : [navigator.language || "en"];
  for (const l of list) {
    const s = l.slice(0, 2).toLowerCase() as Lang;
    if (s in dictionaries) return s;
  }
  return "en";
}
